/// Sparse list of float brightness levels and their corresponding colors.
/// The color will be used for all brightness levels up to the next defined level.
/// Level is a float in the range [0.0, 100.0], where 0.0 is black and 100.0 is white.
using FalseColorMapDataRef = std::span<const std::pair<float, glm::u8vec4>>;

/// A false color map with 256 entries, suitable for use in shaders.
class FalseColorMap {
private:
    std::array<glm::u8vec4, 256> dataLimitedRange{};
    std::array<glm::u8vec4, 256> dataFullRange{};

public:
    FalseColorMap() noexcept = default;

    constexpr FalseColorMap(const FalseColorMapDataRef map) noexcept {
        if (map.empty())
            return;

        // Full Range
        {
            size_t currentIndex = 0;
            for (size_t i = 0; i < map.size() - 1; ++i) {
                const auto& [levelStart, colorStart] = map[i];
                const auto levelEnd                  = map[i + 1].first;
                // Map levels from [0.0, 1.0] to [0, 255]
                const uint8_t indexStart = static_cast<uint8_t>(mapRangeClampOut(levelStart, 0.0f, 100.0f, 0.0f, 255.0f, 0.0f, 255.0f));
                const uint8_t indexEnd   = static_cast<uint8_t>(mapRangeClampOut(levelEnd, 0.0f, 100.0f, 0.0f, 255.0f, 0.0f, 255.0f));

                if (indexEnd < indexStart || indexStart > 255)
                    continue;

                for (size_t j = indexStart; j <= static_cast<size_t>((std::min)(indexEnd, (uint8_t)255)); ++j) {

                    dataFullRange[j] = colorStart;
                    currentIndex     = j;
                }
            }
            // Fill remaining entries with the last color
            for (size_t j = currentIndex + 1; j < 256; ++j) {
                dataFullRange[j] = map.back().second;
            }
        }

        // Limited Range
        {
            size_t currentIndex = 0;
            for (size_t i = 0; i < map.size(); ++i) {
                const auto& [levelStart, colorStart] = map[i];
                const auto levelEnd                  = (i < map.size() - 1) ? map[i + 1].first : 100.f;
                // Map levels from [0.0, 1.0] to [16, 235]
                uint8_t indexStart = static_cast<uint8_t>(mapRangeClampOut(levelStart, 0.0f, 100.0f, 16.0f, 235.0f, 0.0f, 255.0f));
                uint8_t indexEnd   = static_cast<uint8_t>(mapRangeClampOut(levelEnd, 0.0f, 100.0f, 16.0f, 235.0f, 0.0f, 255.0f));
                if (i == 0)
                    indexStart = 0;
                if (i == map.size() - 1)
                    indexEnd = 255;
                if (indexEnd < indexStart || indexStart > 255)
                    continue;
                for (size_t j = indexStart; j <= static_cast<size_t>((std::min)(indexEnd, (uint8_t)255)); ++j) {
                    dataLimitedRange[j] = colorStart;
                    currentIndex        = j;
                }
            }
        }
    }

    [[nodiscard]] constexpr auto GetDataLimitedRange() const noexcept -> const std::array<glm::u8vec4, 256>& {
        return dataLimitedRange;
    }

    [[nodiscard]] constexpr auto GetDataFullRange() const noexcept -> const std::array<glm::u8vec4, 256>& {
        return dataFullRange;
    }
};

